#!/usr/bin/env node
// Fetches the Context7 reference pack described by docs/refs/manifest.json into docs/refs/.
// Usage: node scripts/fetch-refs.mjs [--force] [--only <text>] [--index-only]
// Requires Node >= 22.13 and a Context7 login (`npx ctx7 login`) or CONTEXT7_API_KEY.
import { execFile } from 'node:child_process'
import { existsSync } from 'node:fs'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { promisify } from 'node:util'

const run = promisify(execFile)
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const refsDir = join(root, 'docs', 'refs')
const manifest = JSON.parse(await readFile(join(refsDir, 'manifest.json'), 'utf8'))

const args = process.argv.slice(2)
const force = args.includes('--force')
const indexOnly = args.includes('--index-only')
const only = args.includes('--only') ? args[args.indexOf('--only') + 1] : undefined
const today = new Date().toISOString().slice(0, 10)

const contextId = (e) => (e.version ? `${e.id}/${e.version}` : e.id)
const yaml = (v) => JSON.stringify(String(v))

async function fetchEntry(e) {
  const target = join(refsDir, e.file)
  if (!force && existsSync(target)) return { e, status: 'kept' }
  const cli = ['-y', manifest.tool, 'docs', contextId(e), e.query]
  if (e.language) cli.push('--language', e.language)
  try {
    const { stdout } = await run('npx', cli, { maxBuffer: 32 * 1024 * 1024, timeout: 120_000 })
    const body = stdout.trim()
    if (body.length < 200 || !body.includes('Source:'))
      throw new Error(`unexpected output: ${body.slice(0, 160)}`)
    const header = [
      '---',
      `library: ${yaml(e.library)}`,
      `context7_id: ${yaml(contextId(e))}`,
      `docs_version: ${yaml(e.version ?? 'latest (default branch)')}`,
      `project_version: ${yaml(e.projectVersion)}`,
      `query: ${yaml(e.query)}`,
      `fetched: ${today}`,
      '---',
      '',
      `> Context7 snapshot generated by \`scripts/fetch-refs.mjs\`. Do not edit; change \`docs/refs/manifest.json\` and re-run.`,
      ...(e.note ? ['>', `> Note: ${e.note}`] : []),
      '',
    ].join('\n')
    await mkdir(dirname(target), { recursive: true })
    await writeFile(target, `${header}\n${body}\n`)
    return { e, status: 'fetched' }
  } catch (err) {
    return { e, status: 'failed', error: String(err.message ?? err).split('\n')[0] }
  }
}

async function pool(items, size, fn) {
  const out = []
  let next = 0
  await Promise.all(
    Array.from({ length: size }, async () => {
      while (next < items.length) out.push(await fn(items[next++]))
    }),
  )
  return out
}

function writeIndex() {
  const groups = new Map()
  for (const e of manifest.entries) {
    if (!groups.has(e.group)) groups.set(e.group, [])
    groups.get(e.group).push(e)
  }
  const lines = [
    '# Reference pack',
    '',
    `Context7 snapshots of the official docs this project relies on. Generated by \`node scripts/fetch-refs.mjs\` from \`manifest.json\`; do not edit by hand.`,
    '',
    'Agents: read the matching file here before writing code against a library. If a topic is missing, query Context7 with the pinned ID from this table instead of resolving the library again.',
    '',
  ]
  for (const [group, entries] of groups) {
    lines.push(
      `## ${group}`,
      '',
      '| Topic | Library | Docs version | Project version | Context7 ID |',
      '| --- | --- | --- | --- | --- |',
    )
    for (const e of entries) {
      const title = existsSync(join(refsDir, e.file))
        ? `[${e.topic}](${e.file})`
        : `${e.topic} (not fetched)`
      lines.push(
        `| ${title} | ${e.library} | ${e.version ?? 'latest'} | ${e.projectVersion} | \`${contextId(e)}\` |`,
      )
    }
    const notes = entries.filter((e) => e.note)
    if (notes.length) lines.push('', ...notes.map((e) => `- **${e.topic}**: ${e.note}`))
    lines.push('')
  }
  return writeFile(join(refsDir, 'INDEX.md'), lines.join('\n'))
}

if (!indexOnly) {
  const selected = manifest.entries.filter(
    (e) => !only || e.file.includes(only) || e.library.includes(only),
  )
  const results = await pool(selected, 4, fetchEntry)
  for (const r of results)
    console.log(`${r.status.padEnd(7)} ${r.e.file}${r.error ? `  (${r.error})` : ''}`)
  await writeIndex()
  const failed = results.filter((r) => r.status === 'failed').length
  console.log(
    `\n${results.length} entries: ${results.length - failed} ok, ${failed} failed. Index: docs/refs/INDEX.md`,
  )
  process.exit(failed ? 1 : 0)
}
await writeIndex()
console.log('Index written: docs/refs/INDEX.md')
